import { readdir, readFile, writeFile, access } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { panelDefinitionSchema, settingsSchema, type PanelDefinition } from '../src/shared/panel-definition'

export async function generatePanelCatalog(panelsDir = resolve('src/panels'), outputFile = resolve('src/shared/panel-catalog.generated.ts')) {
  const definitions: PanelDefinition[] = []
  const entries = await readdir(panelsDir, { withFileTypes: true })
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory() || entry.name.startsWith('.')) continue
    const dir = join(panelsDir, entry.name)
    const raw = await readFile(join(dir, 'panel.json'), 'utf8')
    if (raw.length > 65536) throw new Error(`${entry.name}: パネル定義が大きすぎます`)
    const definition = panelDefinitionSchema.parse(JSON.parse(raw))
    if (definition.id !== entry.name) throw new Error(`${entry.name}: フォルダー名とパネルIDが一致しません`)
    if (definition.fields.some(field => field.type === 'select' && new Set(field.options.map(option => option.value)).size !== field.options.length)) throw new Error(`${entry.name}: 選択肢が重複しています`)
    settingsSchema(definition).parse(Object.fromEntries(definition.fields.map(field => [field.key, field.default])))
    await access(join(dir, 'Panel.vue'))
    definitions.push(definition)
  }
  if (definitions.length > 64) throw new Error('パネルの種類が多すぎます')
  const content = `// Generated by scripts/generate-panels.ts. Do not edit.\nimport type { PanelDefinition } from './panel-definition'\nexport const panelCatalog = ${JSON.stringify(definitions, null, 2)} satisfies PanelDefinition[]\n`
  const current = await readFile(outputFile, 'utf8').catch(() => '')
  if (current !== content) await writeFile(outputFile, content)
  return definitions
}
if (import.meta.main) {
  const catalog = await generatePanelCatalog()
  console.log(`Panels: ${catalog.map(panel => panel.id).join(', ')}`)
}
